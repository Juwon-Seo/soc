def rank_model(k, season):
    t = RANKS.get(("GB2", season))
    if t and k in t:
        r, n = t[k]
        return GB2_ELO[r], f"챔피언십 {season} {r}위"
    t = RANKS.get(("GB3", season))
    if t and k in t:
        r, n = t[k]
        if r in GB3_ELO:
            return GB3_ELO[r], f"리그 원(3부) {season} {r}위"
    return None

