    lab = f"브라질 세리에 B {y} {r}위" + (f"/{n}팀" if n != 20 else "") + f" ({extra})"
    man(o, y, half_up(XM["평균"][f"브라질 세리에 B|{y}"] + 51.24 * cv(r, n)), lab)
